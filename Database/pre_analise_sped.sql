IF OBJECT_ID('PRE_ANALISE_REGRA_ITEM', 'U') IS NULL
BEGIN
    CREATE TABLE PRE_ANALISE_REGRA_ITEM (
        ID_PRE_ANALISE_REGRA_ITEM INT IDENTITY(1,1) NOT NULL PRIMARY KEY,
        CODIGO NVARCHAR(60) NOT NULL,
        NOME NVARCHAR(200) NOT NULL,
        UF_DESTINO NVARCHAR(2) NULL,
        CNPJ_FORNECEDOR NVARCHAR(200) NULL,
        NCM_PREFIXO NVARCHAR(8) NULL,
        NCM_EXCECOES NVARCHAR(200) NULL,
        TERMOS_DESCRICAO NVARCHAR(1000) NULL,
        CSTS_APLICAVEIS NVARCHAR(200) NULL,
        CFOPS_APLICAVEIS NVARCHAR(500) NULL,
        RESULTADO NVARCHAR(50) NOT NULL,
        PERCENTUAL_CREDITO DECIMAL(9,4) NULL,
        PRIORIDADE INT NOT NULL CONSTRAINT DF_PRE_ANALISE_REGRA_PRIORIDADE DEFAULT (100),
        FUNDAMENTO_LEGAL NVARCHAR(1000) NULL,
        VIGENCIA_INICIAL DATE NOT NULL,
        VIGENCIA_FINAL DATE NULL,
        ATIVA BIT NOT NULL CONSTRAINT DF_PRE_ANALISE_REGRA_ATIVA DEFAULT (1),
        CONSTRAINT UQ_PRE_ANALISE_REGRA_ITEM_CODIGO UNIQUE (CODIGO)
    );
    CREATE INDEX IX_PRE_ANALISE_REGRA_ITEM_VIGENCIA
        ON PRE_ANALISE_REGRA_ITEM(ATIVA, UF_DESTINO, VIGENCIA_INICIAL, VIGENCIA_FINAL);
END;
GO

