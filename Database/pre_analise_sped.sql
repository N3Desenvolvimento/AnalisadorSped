IF OBJECT_ID('PRE_ANALISE_SPED', 'U') IS NULL
BEGIN
    CREATE TABLE PRE_ANALISE_SPED (
        ID_PRE_ANALISE_SPED INT IDENTITY(1,1) NOT NULL PRIMARY KEY,
        NOME_ARQUIVO NVARCHAR(260) NOT NULL,
        HASH_ARQUIVO NVARCHAR(64) NOT NULL,
        CNPJ NVARCHAR(14) NULL,
        RAZAO_SOCIAL NVARCHAR(200) NULL,
        UF NVARCHAR(2) NULL,
        DT_INI DATE NULL,
        DT_FIN DATE NULL,
        STATUS NVARCHAR(30) NOT NULL CONSTRAINT DF_PRE_ANALISE_SPED_STATUS DEFAULT ('IMPORTADO'),
        IMPORTADO_EM DATETIME2 NOT NULL CONSTRAINT DF_PRE_ANALISE_SPED_DATA DEFAULT (SYSUTCDATETIME()),
        TOTAL_NOTAS_ENTRADA INT NOT NULL CONSTRAINT DF_PRE_ANALISE_SPED_NOTAS DEFAULT (0),
        VALOR_TOTAL_NOTAS DECIMAL(18,2) NOT NULL CONSTRAINT DF_PRE_ANALISE_SPED_VALOR DEFAULT (0),
        BASE_ICMS_TOTAL DECIMAL(18,2) NOT NULL CONSTRAINT DF_PRE_ANALISE_SPED_BASE DEFAULT (0),
        ICMS_CREDITO_TOTAL DECIMAL(18,2) NOT NULL CONSTRAINT DF_PRE_ANALISE_SPED_ICMS DEFAULT (0)
    );
    CREATE INDEX IX_PRE_ANALISE_SPED_HASH ON PRE_ANALISE_SPED(HASH_ARQUIVO);
END;
GO

IF OBJECT_ID('PRE_ANALISE_SPED_NOTA', 'U') IS NULL
BEGIN
    CREATE TABLE PRE_ANALISE_SPED_NOTA (
        ID_PRE_ANALISE_SPED_NOTA INT IDENTITY(1,1) NOT NULL PRIMARY KEY,
        ID_PRE_ANALISE_SPED INT NOT NULL,
        COD_PART NVARCHAR(60) NULL,
        NOME_PARTICIPANTE NVARCHAR(200) NULL,
        CNPJ_PARTICIPANTE NVARCHAR(14) NULL,
        COD_MOD NVARCHAR(2) NULL,
        COD_SIT NVARCHAR(2) NULL,
        SER NVARCHAR(20) NULL,
        NUM_DOC NVARCHAR(20) NULL,
        CHV_NFE NVARCHAR(44) NULL,
        DT_DOC DATE NULL,
        DT_ENTRADA DATE NULL,
        VL_DOC DECIMAL(18,2) NOT NULL CONSTRAINT DF_PRE_ANALISE_SPED_NOTA_DOC DEFAULT (0),
        VL_MERC DECIMAL(18,2) NOT NULL CONSTRAINT DF_PRE_ANALISE_SPED_NOTA_MERC DEFAULT (0),
        VL_BC_ICMS DECIMAL(18,2) NOT NULL CONSTRAINT DF_PRE_ANALISE_SPED_NOTA_BASE DEFAULT (0),
        VL_ICMS DECIMAL(18,2) NOT NULL CONSTRAINT DF_PRE_ANALISE_SPED_NOTA_ICMS DEFAULT (0),
        STATUS_ANALISE NVARCHAR(30) NOT NULL CONSTRAINT DF_PRE_ANALISE_SPED_NOTA_STATUS DEFAULT ('PENDENTE'),
        OBSERVACAO NVARCHAR(2000) NULL,
        CONSTRAINT FK_PRE_ANALISE_SPED_NOTA_ARQUIVO FOREIGN KEY (ID_PRE_ANALISE_SPED)
            REFERENCES PRE_ANALISE_SPED(ID_PRE_ANALISE_SPED) ON DELETE CASCADE
    );
    CREATE INDEX IX_PRE_ANALISE_SPED_NOTA_ARQUIVO ON PRE_ANALISE_SPED_NOTA(ID_PRE_ANALISE_SPED);
    CREATE INDEX IX_PRE_ANALISE_SPED_NOTA_CHAVE ON PRE_ANALISE_SPED_NOTA(CHV_NFE);
END;
GO

